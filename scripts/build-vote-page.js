/**
 * Build vote-page JS and CSS into a server-only module.
 * Output: app/vote-page/dist/vote-assets.server.js
 * Limit: 24 KB combined (JS + CSS). Raised from 15 KB in Task 8 for the swipe deck, welcome and recap screens. Approved by Abbir.
 */

/* global Buffer, process */

import * as esbuild from "esbuild";
import { writeFileSync } from "fs";
import { fileURLToPath } from "url";
import { dirname, join } from "path";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, "..");
const VOTE_PAGE_DIR = join(ROOT, "app", "vote-page");
const DIST_DIR = join(VOTE_PAGE_DIR, "dist");
const SIZE_LIMIT = 24000; // 24 KB

async function build() {
  // Build JS
  const jsResult = await esbuild.build({
    entryPoints: [join(VOTE_PAGE_DIR, "vote.js")],
    bundle: true,
    minify: true,
    write: false,
    format: "iife",
    target: ["es2020"],
  });

  const jsCode = jsResult.outputFiles[0].text;

  // Build CSS
  const cssResult = await esbuild.build({
    entryPoints: [join(VOTE_PAGE_DIR, "vote.css")],
    bundle: true,
    minify: true,
    write: false,
    loader: { ".css": "css" },
  });

  const cssCode = cssResult.outputFiles[0].text;

  // Check combined size
  const jsSize = Buffer.byteLength(jsCode, "utf8");
  const cssSize = Buffer.byteLength(cssCode, "utf8");
  const totalSize = jsSize + cssSize;

  console.log(`vote.js: ${jsSize.toLocaleString()} bytes`);
  console.log(`vote.css: ${cssSize.toLocaleString()} bytes`);
  console.log(`Total: ${totalSize.toLocaleString()} bytes (limit ${SIZE_LIMIT.toLocaleString()})`);

  if (totalSize > SIZE_LIMIT) {
    console.error(`\nBuild failed: combined size ${totalSize} exceeds limit ${SIZE_LIMIT}`);
    process.exit(1);
  }

  // Escape for JS string (backticks) - only escape what's necessary
  const escapeForTemplate = (str) =>
    str.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${");

  // Write server module
  const serverModule = `/**
 * Vote page assets (auto-generated by build-vote-page.js).
 * Do not edit by hand.
 */

export const VOTE_JS = \`${escapeForTemplate(jsCode)}\`;

export const VOTE_CSS = \`${escapeForTemplate(cssCode)}\`;

export const VOTE_ASSETS_SIZE = ${totalSize};
`;

  writeFileSync(join(DIST_DIR, "vote-assets.server.js"), serverModule);
  console.log(`\nWrote app/vote-page/dist/vote-assets.server.js ✓`);
}

build().catch((err) => {
  console.error(err);
  process.exit(1);
});
